pub fn weekday_name(locale: &str, w: chrono::Weekday) -> String {
    use chrono::Weekday::*;
    let key = match w {
        Mon => "weekday.mon",
        Tue => "weekday.tue",
        Wed => "weekday.wed",
        Thu => "weekday.thu",
        Fri => "weekday.fri",
        Sat => "weekday.sat",
        Sun => "weekday.sun",
    };
    t(locale, key)
}
